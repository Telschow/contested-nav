#!/usr/bin/env python3
"""Verify that the benchmark tables in README.md and docs/results.md match the benchmark.

Both documents claim that their numbers are generated rather than typed. This
script is what makes that claim checkable: it re-reads the generated
``results/benchmark.json`` and compares every numeric cell of both tables
against it, so a re-run that moves a number cannot silently leave the prose
describing the old one.

The tables are the only hand-maintained part of the pipeline, and they are
exactly the part most likely to drift, because nothing else fails when they do.

The two-row "Configuration" table in README.md and docs/index.md shows each number twice: over the whole
run and over the GNSS outage window. It is generated by ``--print-configuration-table`` and checked cell by cell
against the same file.

Run after ``scripts/run_benchmark.py``::

    python scripts/check_doc_tables.py
    python scripts/check_doc_tables.py --print-configuration-table
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _fmt(value: float | None, *, percent: bool = False) -> str | None:
    """Format a generated value the way the documents display it."""
    if value is None:
        return None
    return f"{100.0 * value:.1f}%" if percent else f"{value:.3f}"


def _expected_rows(results: dict) -> list[list[str | None]]:
    """One row of four display strings per case, in table order."""
    rows = []
    for case in results["cases"]:
        head = case["headline"]
        coverage = head.get("coverage") or {}
        rows.append(
            [
                _fmt(head.get("ate_rmse_m")),
                _fmt(head.get("claimed_sigma_p_m")),
                _fmt(head.get("nees_mean")) if head.get("nees_mean") is not None else None,
                _fmt(coverage.get("2sigma"), percent=True),
            ]
        )
    return rows


#: The rows of the Configuration table: the label shown, the benchmark case behind it, and whether the row is
#: set in bold (the case the sentence above the table is about).
CONFIGURATION_ROWS = (
    ("GNSS denied, vision off", "outage_control", False),
    ("GNSS denied, vision on", "outage_visual", True),
)
CONFIGURATION_HEADER = (
    "| Configuration | ATE RMSE, full run | Claimed 1σ, full run | Mean NEES, full run (expected 3) "
    "| 2σ-per-axis coverage, full run (expected 99.3%) | Mean NEES, outage window (expected 3) "
    "| 2σ-per-axis coverage, outage window (expected 99.3%) |"
)
CONFIGURATION_SEPARATOR = "|---|---:|---:|---:|---:|---:|---:|"


def _configuration_cells(case: dict) -> list[str]:
    """The six display strings of one Configuration row, from the generated case."""
    head = case["headline"]
    window = case["outage_calibration"]
    return [
        f"{head['ate_rmse_m']:.3f} m",
        f"{head['claimed_sigma_p_m']:.3f} m",
        f"{head['nees_mean']:.1f}",
        f"{100.0 * head['coverage']['2sigma']:.1f}%",
        f"{window['nees_mean']:.1f}",
        f"{100.0 * window['coverage_2sigma']:.1f}%",
    ]


def configuration_table(results: dict) -> str:
    """The Configuration table as Markdown, generated from the benchmark."""
    by_name = {c["name"]: c for c in results["cases"]}
    lines = [CONFIGURATION_HEADER, CONFIGURATION_SEPARATOR]
    for label, name, bold in CONFIGURATION_ROWS:
        cells = _configuration_cells(by_name[name])
        if bold:
            cells = [f"**{c}**" for c in cells]
        lines.append("| " + " | ".join([label, *cells]) + " |")
    return "\n".join(lines)


def _configuration_block(text: str) -> tuple[list[str], list[list[str]]] | None:
    """Header cells and body rows of the table whose first header cell is "Configuration"."""
    lines = text.splitlines()
    for index, line in enumerate(lines):
        cells = _split_pipe(line)
        if cells and cells[0].lower() == "configuration":
            rows = []
            for body in lines[index + 2 :]:
                row = _split_pipe(body)
                if not row:
                    break
                rows.append(row)
            return cells, rows
    return None


def check_configuration(results_path: Path, documents: list[Path]) -> int:
    """Check the Configuration table of each document against the generated benchmark."""
    results = json.loads(results_path.read_text())
    by_name = {c["name"]: c for c in results["cases"]}
    failures: list[str] = []
    for document in documents:
        name = _display(document)
        if not document.exists():
            failures.append(f"{name}: missing")
            continue
        block = _configuration_block(document.read_text())
        if block is None:
            failures.append(f"{name}: no Configuration table")
            continue
        header, rows = block
        want_header = _split_pipe(CONFIGURATION_HEADER)
        if header != want_header:
            failures.append(f"{name}: Configuration header is {header}, expected {want_header}")
        if [r[0] for r in rows] != [label for label, _, _ in CONFIGURATION_ROWS]:
            failures.append(f"{name}: Configuration rows are {[r[0] for r in rows]}")
            continue
        for row, (label, case_name, _bold) in zip(rows, CONFIGURATION_ROWS, strict=True):
            want = _configuration_cells(by_name[case_name])
            got = [c.replace("**", "") for c in row[1:]]
            for column, (g, w) in enumerate(zip(got, want, strict=False), start=1):
                if g != w:
                    failures.append(
                        f"{name}: {label} column {column} ({header[column]}): document says {g}, generated value is {w}"
                    )
            if len(got) != len(want):
                failures.append(f"{name}: {label}: {len(got)} cells, expected {len(want)}")
    if failures:
        print("Configuration tables disagree with the generated benchmark:", file=sys.stderr)
        for failure in failures:
            print(f"  {failure}", file=sys.stderr)
        print(
            "\ntake the table from `python scripts/check_doc_tables.py --print-configuration-table`.", file=sys.stderr
        )
        return 1
    print(f"Configuration tables match {_display(results_path)} in {', '.join(_display(p) for p in documents)}")
    return 0


def _markdown_cells(text: str) -> list[list[str]]:
    """Body rows of the benchmark table in README.md, as cell lists."""
    lines = text.splitlines()
    start = None
    for index, line in enumerate(lines):
        cells = _split_pipe(line)
        if cells and cells[0].lower().startswith("scenario") and any("ate rmse" in c.lower() for c in cells):
            start = index + 2  # skip the header and the |---| separator
            break
    if start is None:
        return []
    rows = []
    for line in lines[start:]:
        cells = _split_pipe(line)
        if not cells:
            break
        if all(set(c) <= set("-: ") for c in cells):  # a second separator
            continue
        rows.append(cells)
    return rows


def _split_pipe(line: str) -> list[str]:
    stripped = line.strip()
    if not stripped.startswith("|"):
        return []
    return [cell.strip() for cell in stripped.strip("|").split("|")]


def _html_cells(text: str) -> list[list[str]]:
    """Body rows of the benchmark table in docs/index.html, as cell lists."""
    body = re.search(r"<tbody>(.*?)</tbody>", text, re.S)
    if not body:
        return []
    rows = []
    for row in re.findall(r"<tr>(.*?)</tr>", body.group(1), re.S):
        cells = [
            re.sub(r"<[^>]+>", "", c).replace("&sigma;", "sigma").strip()
            for c in re.findall(r"<td[^>]*>(.*?)</td>", row, re.S)
        ]
        if cells:
            rows.append(cells)
    return rows


def _cell(rows: list[list[str]], index: int, column: int) -> str | None:
    try:
        return rows[index][column]
    except IndexError:
        return None


def _display(path: Path) -> str:
    """Repo-relative when possible, absolute otherwise.

    Documents passed with --document may live outside the repository, and a
    reporting helper must not raise while reporting a mismatch.
    """
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def check(results_path: Path, documents: list[Path]) -> int:
    results = json.loads(results_path.read_text())
    expected = _expected_rows(results)
    failures: list[str] = []

    columns = ("ATE RMSE", "claimed 1 sigma", "mean NEES", "coverage")
    for document in documents:
        if not document.exists():
            failures.append(f"{document}: missing")
            continue
        text = document.read_text()
        found = _html_cells(text) if document.suffix == ".html" else _markdown_cells(text)
        name = _display(document)
        if len(found) != len(expected):
            failures.append(f"{name}: {len(found)} benchmark rows, expected {len(expected)}")
            continue
        for index, want in enumerate(expected):
            case = results["cases"][index]["name"]
            for column, w in zip(columns, want, strict=False):
                got = _cell(found, index, columns.index(column) + 1)
                if w is None:
                    # A case with no reported covariance shows "n/a" in the docs.
                    if got is not None and got not in ("n/a", "n.a"):
                        failures.append(f"{name}: {case} {column}: expected n/a, found {got}")
                    continue
                want_text = f"{float(w):.1f}" if column == "mean NEES" else w
                if got is None or not got.startswith(want_text):
                    failures.append(f"{name}: {case} {column}: document says {got}, generated value is {want_text}")

    if failures:
        print("documentation tables disagree with the generated benchmark:", file=sys.stderr)
        for failure in failures:
            print(f"  {failure}", file=sys.stderr)
        print(
            "\nregenerate with scripts/run_benchmark.py and update the tables by hand,\n"
            "or take the values from `python scripts/run_benchmark.py --markdown`.",
            file=sys.stderr,
        )
        return 1

    checked = ", ".join(_display(p) for p in documents)
    print(f"documentation tables match {_display(results_path)} ({len(expected)} cases) in {checked}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=ROOT / "results" / "benchmark.json")
    parser.add_argument("--document", type=Path, action="append", dest="documents")
    parser.add_argument(
        "--print-configuration-table", action="store_true", help="print the generated Configuration table and exit"
    )
    args = parser.parse_args(argv)

    if not args.results.exists():
        print(f"{args.results} not found; run scripts/run_benchmark.py first", file=sys.stderr)
        return 1
    if args.print_configuration_table:
        print(configuration_table(json.loads(args.results.read_text())))
        return 0
    if args.documents:
        return check(args.results, args.documents)
    scenario = check(args.results, [ROOT / "README.md", ROOT / "docs" / "results.md"])
    configuration = check_configuration(args.results, [ROOT / "README.md", ROOT / "docs" / "index.md"])
    return scenario or configuration


if __name__ == "__main__":
    raise SystemExit(main())
